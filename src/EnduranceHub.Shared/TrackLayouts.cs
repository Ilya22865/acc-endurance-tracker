    public static (double X, double Y) InterpolatePosition(
        IReadOnlyList<(double X, double Y)> outline, double splinePosition)
    {
        if (outline.Count < 2) return (0.5, 0.5);
        var s = Math.Clamp(splinePosition, 0.0, 0.9999);
        var totalSegments = outline.Count;
        var rawIndex = s * totalSegments;
        var index = (int)rawIndex;
        var frac = rawIndex - index;
        var p1 = outline[index];
        var p2 = outline[(index + 1) % outline.Count];
        return (p1.X + frac * (p2.X - p1.X), p1.Y + frac * (p2.Y - p1.Y));
    }
