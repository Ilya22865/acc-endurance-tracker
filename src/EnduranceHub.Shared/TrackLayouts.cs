    public static string Normalize(string trackName)
    {
        var n = (trackName ?? "").Trim().ToLowerInvariant();
        n = n.Replace("ä", "a").Replace("ö", "o").Replace("ü", "u").Replace("ß", "ss");
        return new string(n.Where(char.IsLetterOrDigit).ToArray());
    }

    public static IReadOnlyList<(double X, double Y)> GetOutline(string trackName, int trackMeters = 0)
    {
        var key = Normalize(trackName);
        if (key.Contains("nurburgring"))
        {
            // 24h-трасса (~20.8 км) vs GP (~5.1 км)
            if (trackMeters >= 12000 || key.Contains("24h") || key.Contains("gesamt"))
                return _n24;
        }

        if (_layouts.TryGetValue(key, out var layout)) return layout;

        // приближённые схемы для известных трасс
        var approx = key switch
        {
            "spa" => SPA,
            "zandvoort" => ZANDVOORT,
            "barcelona" => BARCELONA,
            "silverstone" => SILVERSTONE,
            _ => null,
        };
        return approx ?? _genericOval;
    }

